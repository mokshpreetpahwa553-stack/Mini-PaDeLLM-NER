"""
This module parses the raw structured output generated by autoreg_struct.
After inference, the model produces one generation for each validation
sentence, such as:
ORG: Apple <sep> PER: John Smith <sep> MISC: <none> <sep> LOC: Dublin

This module checks whether that generation follows the expected autoreg_struct
format and classifies it as:

- valid: the generation contains all four labels in the correct order,
  and each label has either entity mentions or <none>.
- empty: the model generated no usable text.
- malformed: the generation is not empty but does not follow the expected
  format, for example a missing colon, missing label, wrong label order,
  or incorrect use of <sep>.

The parser works on one generation at a time. It does not read the JSONL
predictions file and does not calculate total valid, empty, or malformed
counts; those totals are calculated by the evaluation script.

The parser does not decide whether predicted entities are correct. It only
checks whether the model followed the required output format.
"""

def autoreg_parser(output):
    label_order=["ORG", "PER", "MISC", "LOC"]

    output=output.strip()

    if output=="":
        return {"status":"empty","entities": []}

    
    positions=[]
    position=0
    for label in label_order:
        marker=label+":"
        label_position=output.find(marker,position)

        if label_position==-1:
            return {"status":"malformed","reason":"missing_labels"}
        positions.append(label_position)
        position=label_position+1

    #checking order of labels
    for i in range(len(positions)-1):
        if positions[i]>=positions[i+1]:
            return {"status":"malformed","entities":"[]"}

    dic={}
    dic["status"]="valid"
    entities={}
    for i,idx in enumerate(positions):
        lst=[]
        label=label_order[i]
        value_start=positions[i]+len(label)+1 #+1 for :
        if i<len(positions)-1:
            value_end=positions[i+1]
        else:
            value_end=len(output)

        value=output[value_start:value_end].strip()

        #removing <sep> from end
        if value.endswith("<sep>"):
            value = value[:len(value)-len("<sep>")].strip()
            
        if value =="<none>":
            entities[label]=[]
        elif value=="":
            return {
            "status": "malformed",
            "entities": []
            }
        else:
            lst = value.split("<sep>")
            cleaned_lst=[]
            for word in lst:
                cleaned_lst.append(word.strip())
            
            entities[label]=cleaned_lst
    
    dic["entities"]=entities
    return dic

                
